"""Generate exact table/column profiles for raw Olist tables."""

from pathlib import Path

import duckdb

DB_PATH = "db/olist.duckdb"  # change to your database file location
SCHEMAS = ("raw",)  # change to match your schemas
OUT = Path("docs/olist/profile")
OUT.mkdir(parents=True, exist_ok=True)

con = duckdb.connect(DB_PATH, read_only=True)
in_list = ",".join(repr(s) for s in SCHEMAS)
tables = con.execute(
    "SELECT table_schema, table_name FROM information_schema.tables "
    f"WHERE table_schema IN ({in_list}) ORDER BY 1, 2"
).fetchall()

RANGE_TYPES = ("INT", "DECIMAL", "DOUBLE", "FLOAT", "DATE", "TIMESTAMP")
index = ["# Table index (auto-generated)\n", "| table | rows | columns |", "|---|---|---|"]

for schema, table in tables:
    cols = con.execute(
        "SELECT column_name, data_type FROM information_schema.columns "
        "WHERE table_schema=? AND table_name=? ORDER BY ordinal_position",
        [schema, table],
    ).fetchall()
    parts = ["count(*)"]
    for c, dt in cols:
        parts.append(f'count(*) - count("{c}")')
        parts.append(f'count(DISTINCT "{c}")')
        if any(k in dt.upper() for k in RANGE_TYPES):
            parts.append(f'min("{c}")::VARCHAR')
            parts.append(f'max("{c}")::VARCHAR')
    row = con.execute(f'SELECT {", ".join(parts)} FROM "{schema}"."{table}"').fetchone()
    n, i = row[0], 1
    lines = [
        f"# {schema}.{table}",
        f"Rows: {n}. Auto-generated by scripts/profile_olist.py, do not edit manually.\n",
        "| column | type | null % | distinct | min | max |",
        "|---|---|---|---|---|---|",
    ]
    for c, dt in cols:
        nulls, nd = row[i], row[i + 1]
        i += 2
        mn = mx = ""
        if any(k in dt.upper() for k in RANGE_TYPES):
            mn, mx = row[i], row[i + 1]
            i += 2
        pct = f"{100 * nulls / n:.1f}" if n else "0"
        lines.append(f"| {c} | {dt} | {pct} | {nd} | {mn} | {mx} |")
    (OUT / f"{schema}.{table}.md").write_text("\n".join(lines), encoding="utf-8")
    index.append(f"| {schema}.{table} | {n} | {len(cols)} |")

(OUT / "_index.md").write_text("\n".join(index), encoding="utf-8")
print(f"Done: {len(tables)} tables")
